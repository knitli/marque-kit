"""Pair the selected-audience reader with an engine build's recipient register.

See apps/office-addin/README.md for the deployment contract. The generated
values.rs must be taken from the same build as the supplied engine artifact.
"""

import argparse
import hashlib
import re
from pathlib import Path


def sha256_file(path):
    digest = hashlib.sha256()
    with path.open('rb') as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def extract(path):
    if path.stat().st_size > 16 * 1024 * 1024:
        raise ValueError('generated values.rs exceeds the extraction limit')
    text = path.read_text(encoding='utf-8')
    tables = re.findall(r'pub static TRIGRAPHS: &\[&str\] = &\[(.*?)\];', text, re.DOTALL)
    if len(tables) != 1 or not re.fullmatch(r'(?:\s*"[A-Z0-9_]{2,16}",\s*)+', tables[0]):
        raise ValueError('expected exactly one generated recipient register')
    codes = re.findall(r'"([A-Z0-9_]{2,16})"', tables[0])
    if codes != sorted(set(codes)):
        raise ValueError('recipient register must be sorted and unique')
    return codes


def render(codes, engine_commit, source_hash, engine_hash):
    digest = hashlib.sha256(('\n'.join(codes) + '\n').encode('ascii')).hexdigest()
    entries = ''.join(f"  '{code}',\n" for code in codes)
    metadata = (
        ('FileCopyrightText', '2026 Knitli Inc.'),
        ('License-Identifier', 'AGPL-3.0-only'),
    )
    header = ''.join(f'// SPDX-{field}: {value}\n' for field, value in metadata)
    return (
        f'{header}\n'
        '// Generated by fixtures/extract-selected-audience-vocabulary.py; do not edit.\n'
        f'// Engine commit: {engine_commit}\n'
        f'// Build-generated values.rs SHA-256: {source_hash}\n'
        '// Register digest is SHA-256 of sorted codes, each followed by LF.\n'
        f"export const SELECTED_AUDIENCE_VOCABULARY_SHA256 = '{digest}';\n"
        f"export const SELECTED_AUDIENCE_ENGINE_SHA256 = '{engine_hash}';\n"
        'export const SELECTED_AUDIENCE_RECIPIENTS: readonly string[] = Object.freeze([\n'
        f'{entries}'
        ']);\n\n'
        'const recipients = new Set(SELECTED_AUDIENCE_RECIPIENTS);\n\n'
        'export function isSelectedAudienceRecipient(value: string): boolean {\n'
        '  return recipients.has(value);\n'
        '}\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('values', type=Path, help='values.rs generated by the paired engine build')
    parser.add_argument('engine', type=Path, help='exact engine artifact to be deployed')
    parser.add_argument('engine_commit', help='40-character commit of the engine build')
    parser.add_argument('--check', action='store_true', help='verify the checked-in output without changing it')
    args = parser.parse_args()
    if not re.fullmatch(r'[0-9a-f]{40}', args.engine_commit):
        parser.error('engine_commit must be a full lowercase Git commit ID')
    result = render(extract(args.values), args.engine_commit, sha256_file(args.values), sha256_file(args.engine))
    output = Path(__file__).resolve().parent.parent / 'apps/office-addin/src/selected-audience-vocabulary.ts'
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != result:
            raise SystemExit('selected-audience vocabulary or engine artifact does not match this build')
    else:
        output.write_text(result, encoding='utf-8')


if __name__ == '__main__':
    main()
